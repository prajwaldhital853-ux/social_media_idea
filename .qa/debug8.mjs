import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--autoplay-policy=no-user-gesture-required'] });
const p = await browser.newPage();
await p.setViewport({ width: 1280, height: 900 });
p.on('console', m => console.log('CONSOLE:', m.text().slice(0, 160)));
p.on('framenavigated', f => { if (f === p.mainFrame()) console.log('NAVIGATED:', f.url()); });
p.on('pageerror', e => console.log('PAGEERROR', e.message));
const sleep = ms => new Promise(r => setTimeout(r, ms));
await p.goto('http://localhost:3000/', { waitUntil: 'domcontentloaded' });
await sleep(1200);
await p.evaluate(() => {
  window.addEventListener('popstate', e => console.log('POPSTATE state=' + JSON.stringify(e.state) + ' hist=' + history.length));
  const origBack = history.back.bind(history);
  history.back = () => { console.log('BACK() hist=' + history.length); origBack(); };
  const origPush = history.pushState.bind(history);
  history.pushState = (s, t, u) => { console.log('PUSH ' + JSON.stringify(s) + ' hist=' + history.length); origPush(s, t, u); };
});
await p.evaluate(() => { [...document.querySelectorAll('article.post')].find(a => a.textContent.includes('Weekend in Pokhara')).querySelector('.post-video .video-play').click(); });
await sleep(800);
await p.evaluate(() => document.querySelector('.media-viewer-actions .media-comment-btn').click());
await sleep(600);
await p.type('.comments-overlay .comments-compose input', 'dbg');
await p.evaluate(() => document.querySelector('.comments-overlay button[type="submit"]').click());
await sleep(400);
console.log('--- pressing Escape ---');
await p.keyboard.press('Escape');
await sleep(900);
console.log('final:', await p.evaluate(() => ({ sheet: !!document.querySelector('.comments-overlay'), modal: !!document.querySelector('.media-modal'), hist: history.length, url: location.href })));
await browser.close();
